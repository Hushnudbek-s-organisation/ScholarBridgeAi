/**
 * Advanced Essay AI (#8) — the scoring half.
 *
 * The rubric is computed here, deterministically, from the text itself. The
 * model writes feedback prose; it does not decide the numbers. A student who
 * improves their draft must see the score move for a reason they can verify,
 * and two readers must get the same score from the same text.
 *
 * Pure module — asserted in `scripts/check-essays.ts`.
 */

export type EssayType = "sop" | "personal_statement" | "why_us" | "supplemental" | "scholarship";

export interface RubricScores {
  /** Does the first paragraph earn the reader's attention? */
  hook: number;
  /** Paragraphs, progression, a clear ending. */
  structure: number;
  /** Transitions and references between consecutive paragraphs. */
  flow: number;
  /** Numeric and other detectable evidence cues vs. generic claims (not full semantic review). */
  specificity: number;
  /** Sentence variety, passive voice, cliché density, typos. */
  language: number;
  /** The action-to-weak-verb balance (a writing cue, not a quality verdict). */
  agency: number;
  /** Does it answer the prompt and name the programme? */
  fit: number;
  total: number;
}

export interface EssayFeedback {
  scores: RubricScores;
  wordCount: number;
  /** Each item is something the student can act on. */
  issues: { code: string; message: string; severity: "blocker" | "warning" | "info"; excerpt?: string; params?: Record<string, string | number> }[];
  /** Words that weaken the essay — with where they appear. */
  cliches: { phrase: string; count: number }[];
  flowAnalysis: { linkedParagraphs: number; paragraphTransitions: number; transitionExamples: string[]; stageSequence: string[]; backwardJumps: number };
  actionVerbs: {
    activeCount: number;
    weakCount: number;
    ratioPct: number | null;
    activeExcerpts: { verb: string; excerpt: string }[];
    weakExcerpts: { phrase: string; excerpt: string }[];
  };
  promptCoverage: {
    source: "custom_prompt" | "essay_type";
    covered: string[];
    missing: string[];
    questions: string[];
  };
  readingTimeSec: number;
}

export interface EssayOptions {
  type?: EssayType;
  /** Word limit published by the programme, when there is one. */
  wordLimit?: number | null;
  /** The university or programme the essay is addressed to. */
  targetName?: string | null;
  /** Exact prompt text when the student has it; never generated by the model. */
  prompt?: string | null;
}

// --- Text helpers ----------------------------------------------------------

export function countWords(text: string): number {
  const words = text.trim().split(/\s+/).filter((w) => /[a-z\u0400-\u04ff]/i.test(w));
  return words.length;
}

export function sentences(text: string): string[] {
  return text
    .split(/(?<=[.!?])\s+|\n+/)
    .map((s) => s.trim())
    .filter((s) => s.length > 1);
}

export function paragraphs(text: string): string[] {
  return text
    .split(/\n\s*\n/)
    .map((p) => p.trim())
    .filter((p) => p.length > 0);
}

const FLOW_STAGES: { key: string; re: RegExp }[] = [
  { key: "motivation", re: /\b(?:why|motivat|interest|curious|drawn to|chose|choose|inspir|passion)\b/i },
  { key: "preparation", re: /\b(?:coursework|studied|learned|trained|degree|education|academic|prepared|skills|course|class)\b/i },
  { key: "evidence", re: /\b(?:research|project|built|led|developed|designed|published|data|tested|team|prototype|implemented|results|outcome|engineered|automated)\b/i },
  { key: "programme_fit", re: /\b(?:program(?:me)?|university|faculty|professor|laboratory|lab|curriculum|module)\b/i },
  { key: "future_impact", re: /\b(?:after graduation|career|future|goal|intend|plan to|aim to|contribut|impact|hope to build|will work)\b/i },
];

function paragraphStage(paragraph: string): string | null {
  // Prefer a specific programme/future/evidence signal over generic motivation
  // words that often appear incidentally in the same paragraph.
  const matches = FLOW_STAGES.filter((stage) => stage.re.test(paragraph));
  return matches.length ? matches[matches.length - 1].key : null;
}

function analyzeFlow(text: string): { score: number; issues: EssayFeedback["issues"]; analysis: EssayFeedback["flowAnalysis"] } {
  const paras = paragraphs(text);
  const issues: EssayFeedback["issues"] = [];
  const paragraphTransitions = Math.max(0, paras.length - 1);
  let linkedParagraphs = 0;
  const transitionExamples: string[] = [];
  const transitionCounts = new Map<string, number>();
  for (const paragraph of paras.slice(1)) {
    const first = sentences(paragraph)[0] ?? paragraph;
    const leading = FLOW_TRANSITIONS.exec(first.trim());
    const referencesEarlier = FLOW_REFERENCES.test(first);
    if (leading || referencesEarlier) linkedParagraphs++;
    if (leading) {
      const label = leading[0].toLowerCase();
      transitionExamples.push(first.slice(0, 180));
      transitionCounts.set(label, (transitionCounts.get(label) ?? 0) + 1);
    } else if (referencesEarlier) {
      transitionExamples.push(first.slice(0, 180));
    }
  }

  const stageSequence = paras.map(paragraphStage).filter((stage): stage is string => stage != null);
  let backwardJumps = 0;
  for (let i = 1; i < stageSequence.length; i++) {
    const prior = FLOW_STAGES.findIndex((stage) => stage.key === stageSequence[i - 1]);
    const current = FLOW_STAGES.findIndex((stage) => stage.key === stageSequence[i]);
    if (current < prior) backwardJumps++;
  }

  const linkRatio = paragraphTransitions > 0 ? linkedParagraphs / paragraphTransitions : null;
  let score = linkRatio == null
    ? 60
    : clamp((paragraphTransitions >= 3 ? 42 : 55) + linkRatio * (paragraphTransitions >= 3 ? 50 : 35), 0, 100);
  // Reward a coherent, forward-moving story only when enough distinct topic
  // stages can actually be detected; absence of a topic is never a penalty.
  if (stageSequence.length >= 3) {
    const progressionScore = clamp(100 - backwardJumps * 25, 0, 100);
    score = clamp(score * 0.7 + progressionScore * 0.3, 0, 100);
  }

  const disconnectedFlow = paras.length >= 3 && linkRatio != null && linkRatio < 0.34;
  const coherentStageSequence = stageSequence.length >= 3 && backwardJumps === 0;
  if ((disconnectedFlow && !coherentStageSequence) || backwardJumps > 0) {
    issues.push({
      code: "abrupt_paragraph_flow",
      message: "Some paragraph boundaries lack a detectable transition, or the topic sequence moves backwards. Check whether the progression is clear to a reader; not every paragraph needs a transition word.",
      severity: "info",
      excerpt: issueExcerpt(sentences(paras[1] ?? "")[0] ?? paras[1] ?? ""),
    });
  }
  const repeated = [...transitionCounts.entries()].find(([, count]) => count >= 3);
  if (repeated) {
    issues.push({
      code: "repeated_transition",
      message: `The transition “${repeated[0]}” appears ${repeated[1]} times at paragraph openings. Vary the connection only where it improves clarity.`,
      severity: "info",
      excerpt: issueExcerpt(transitionExamples.find((example) => example.toLowerCase().startsWith(repeated[0])) ?? ""),
    });
  }
  return {
    score,
    issues,
    analysis: { linkedParagraphs, paragraphTransitions, transitionExamples: transitionExamples.slice(0, 5), stageSequence, backwardJumps },
  };
}

function analyzeActionVerbs(text: string): { score: number; issues: EssayFeedback["issues"]; feedback: EssayFeedback["actionVerbs"] } {
  const activeExcerpts: EssayFeedback["actionVerbs"]["activeExcerpts"] = [];
  const weakExcerpts: EssayFeedback["actionVerbs"]["weakExcerpts"] = [];
  let activeCount = 0;
  let weakCount = 0;
  const ss = sentences(text);
  for (const sentence of ss) {
    for (const item of ACTIVE_VERBS) {
      const matches = [...sentence.matchAll(new RegExp(item.re.source, "gi"))];
      activeCount += matches.length;
      if (matches.length && activeExcerpts.length < 6) {
        activeExcerpts.push({ verb: matches[0][0].toLowerCase(), excerpt: issueExcerpt(sentence, 220) });
      }
    }
    for (const item of WEAK_VERBS) {
      const matches = [...sentence.matchAll(new RegExp(item.re.source, "gi"))];
      weakCount += matches.length;
      if (matches.length && weakExcerpts.length < 6) {
        weakExcerpts.push({ phrase: matches[0][0].toLowerCase(), excerpt: issueExcerpt(sentence, 220) });
      }
    }
  }
  const denominator = activeCount + weakCount;
  const ratioPct = denominator > 0 ? Math.round((activeCount / denominator) * 100) : null;
  const score = ratioPct == null ? 55 : clamp(35 + ratioPct * 0.65, 0, 100);
  const issues: EssayFeedback["issues"] = [];
  if (ratioPct != null && ratioPct < 50 && weakCount > 0) {
    issues.push({
      code: "action_verb_balance",
      message: `The simple verb check found ${activeCount} action verb${activeCount === 1 ? "" : "s"} and ${weakCount} weaker/less-specific phrase${weakCount === 1 ? "" : "s"}. Where accurate, say exactly what you did; keep a softer verb when it is more truthful.`,
      severity: "info",
      excerpt: weakExcerpts[0]?.excerpt,
    });
  }
  return { score, issues, feedback: { activeCount, weakCount, ratioPct, activeExcerpts, weakExcerpts } };
}

function promptCoverage(text: string, opts: EssayOptions): EssayFeedback["promptCoverage"] {
  const customPrompt = (opts.prompt ?? "").trim();
  const source: EssayFeedback["promptCoverage"]["source"] = customPrompt ? "custom_prompt" : "essay_type";
  const requested = customPrompt
    ? PROMPT_ELEMENTS.filter((element) => element.prompt.test(customPrompt)).map((element) => element.key)
    : [...TYPE_PROMPT_ELEMENTS[opts.type ?? "sop"]];
  const uniqueRequested = [...new Set(requested.length ? requested : ["direct_response"])];
  const covered: string[] = [];
  const missing: string[] = [];
  for (const key of uniqueRequested) {
    const element = PROMPT_ELEMENTS.find((candidate) => candidate.key === key);
    if (element?.response.test(text)) covered.push(key);
    else missing.push(key);
  }
  return { source, covered, missing, questions: missing };
}

/** A short passage copied from the submitted draft for grounded feedback. */
function issueExcerpt(text: string, max = 180): string {
  const trimmed = text.trim();
  const excerpt = trimmed.slice(0, max).replace(/\s+/g, " ");
  return trimmed.length > max ? `${excerpt}…` : excerpt;
}

